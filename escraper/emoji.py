def add_emoji(title):
    pool = []

    for word, emojis in emoji_dict.items():
        if word == "другое":
            continue
        if word in title.lower():
            pool.extend(emojis)

    if not pool:
        pool = emoji_dict["другое"]

    return f"{random.choice(pool)} {title}"
